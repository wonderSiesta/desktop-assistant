import { contextBridge, ipcRenderer } from 'electron'

contextBridge.exposeInMainWorld('electronAPI', {
  // Window controls
  minimize: () => ipcRenderer.send('window-minimize'),
  maximize: () => ipcRenderer.send('window-maximize'),
  close: () => ipcRenderer.send('window-close'),
  isMaximized: () => ipcRenderer.invoke('window-is-maximized'),
  petGet:()=>ipcRenderer.invoke('pet-get'),
  petPresetSelect:(id:string)=>ipcRenderer.invoke('pet-preset-select',id),
  petSkinGet:()=>ipcRenderer.invoke('pet-skin-get'),
  petSkinChoose:()=>ipcRenderer.invoke('pet-skin-choose'),
  petSkinReset:()=>ipcRenderer.invoke('pet-skin-reset'),
  petConfigure:(patch:unknown)=>ipcRenderer.invoke('pet-configure',patch),
  petInteract:(action:string)=>ipcRenderer.invoke('pet-interact',action),
  petToggle:()=>ipcRenderer.invoke('pet-toggle'),
  petMenu:()=>ipcRenderer.send('pet-menu'),
  petRestore:()=>ipcRenderer.send('pet-restore'),
  petHide:(ms?:number)=>ipcRenderer.invoke('pet-hide',ms),
  petOpenMain:(id?:string,filter?:string)=>ipcRenderer.invoke('pet-open-main',id,filter),
  petMarkSeen:()=>ipcRenderer.invoke('pet-seen'),
  petPanelMode:(mode:string)=>ipcRenderer.invoke('pet-panel-mode',mode),
  petPanelClose:()=>ipcRenderer.send('pet-panel-close'),
  petQuit:()=>ipcRenderer.send('pet-quit'),
  petIgnore:(ignore:boolean)=>ipcRenderer.send('pet-ignore',ignore),
  petDragStart:()=>ipcRenderer.send('pet-drag-start'),
  petDragEnd:(cancelled?:boolean)=>ipcRenderer.invoke('pet-drag-end',cancelled),
  mainTargetGet:()=>ipcRenderer.invoke('main-target-get'),
  onMainNavigate:(listener:(target:unknown)=>void)=>{const handler=(_event:unknown,target:unknown)=>listener(target);ipcRenderer.on('main-navigate',handler);return ()=>ipcRenderer.removeListener('main-navigate',handler)},
  onPetState:(listener:(state:unknown)=>void)=>{const handler=(_event:unknown,state:unknown)=>listener(state);ipcRenderer.on('pet-state',handler);return ()=>ipcRenderer.removeListener('pet-state',handler)},
  capturesGet: () => ipcRenderer.invoke('captures-get'),
  capturesImport: () => ipcRenderer.invoke('captures-import'),
  capturesConfigure: (patch: unknown) => ipcRenderer.invoke('captures-configure',patch),
  capturesUpdate: (ids:string[],patch:unknown) => ipcRenderer.invoke('captures-update',ids,patch),
  capturesImage: (id:string) => ipcRenderer.invoke('captures-image',id),
  capturesCopy: (id:string) => ipcRenderer.invoke('captures-copy',id),
  capturesExport: (ids:string[]) => ipcRenderer.invoke('captures-export',ids),
  capturesFolder: () => ipcRenderer.invoke('captures-folder'),
  capturesEmptyTrash: () => ipcRenderer.invoke('captures-empty-trash'),
  capturesSnipping: () => ipcRenderer.invoke('captures-snipping'),
  capturesTopmost: (enabled:boolean) => ipcRenderer.invoke('captures-topmost',enabled),
  onCapturesChanged: (listener:()=>void) => { const handler=()=>listener();ipcRenderer.on('captures-changed',handler);return ()=>ipcRenderer.removeListener('captures-changed',handler) },

  // Popup window
  popupOpen: (appNames: string[]) => ipcRenderer.send('popup-open', appNames),
  popupClose: () => ipcRenderer.send('popup-close'),
  popupIsOpen: () => ipcRenderer.invoke('popup-is-open'),

  // Global hotkey
  hotkeyGet: () => ipcRenderer.invoke('hotkey-get'),
  hotkeySet: (enabled: boolean, accelerator: string) => ipcRenderer.invoke('hotkey-set', enabled, accelerator),
  hotkeyPause: () => ipcRenderer.send('hotkey-pause'),
  hotkeyResume: () => ipcRenderer.send('hotkey-resume'),

  // System tools
  launchApp: (cmd: string) => ipcRenderer.invoke('launch-app', cmd),
  clipboardRead: () => ipcRenderer.invoke('clipboard-read'),
  clipboardWrite: (text: string) => ipcRenderer.invoke('clipboard-write', text),
  clipboardReadImage: () => ipcRenderer.invoke('clipboard-read-image'),
  clipboardWriteImage: (dataUrl: string) => ipcRenderer.invoke('clipboard-write-image', dataUrl),
  clipboardHistoryGet: () => ipcRenderer.invoke('clipboard-history-get'),
  clipboardHistoryDelete: (id: string) => ipcRenderer.invoke('clipboard-history-delete', id),
  clipboardHistoryClear: () => ipcRenderer.invoke('clipboard-history-clear'),
  clipboardHistoryDeleteBefore: (cutoff: number) => ipcRenderer.invoke('clipboard-history-delete-before', cutoff),
  fileSearch: (query: string) => ipcRenderer.invoke('file-search', query),

  // Schedules
  getSchedules: () => ipcRenderer.invoke('get-schedules'),
  addSchedule: (schedule: unknown) => ipcRenderer.invoke('add-schedule', schedule),
})
